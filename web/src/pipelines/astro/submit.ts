// The submit file for one FITS preview job.
//
// One job per image in "each" mode, one job over all of them in
// "composite" mode. The job count is small by construction, so this
// pipeline stays a plain submission rather than a DAG -- see
// pipelines/blast when the inputs are shared and large.

import { adString, isSafeFileName, quote } from '../../lib/submit';
import { OUTPUT_FILES, RUNNER_FILE } from './runner';
import { requestDiskKB, requestMemoryMB } from './fits';

/** Every batch name this pipeline makes starts with this. */
export const BATCH_PREFIX = 'fitsprev-';

const REQUEST_CPUS = 1;

/**
 * The image the job runs in, because the job needs astropy.
 *
 * This pipeline used to hope the execute node had astropy installed
 * and, when it did not, told the user to "ask your system
 * administrator" -- an answer that is useless to the person reading it
 * and avoidable, since naming an image is one submit command.
 *
 * `continuumio/anaconda3:2024.10-1` carries astropy 6.1.3 and numpy
 * 1.26.4 on Python 3.12.7, verified by pulling the image and running
 * it rather than by reading its description. The tag is PINNED:
 * `latest` is the same manifest digest today and will not be forever,
 * and an image that changes underneath a pipeline breaks it for
 * reasons nobody can see from here.
 *
 * Anaconda is a four-gigabyte image for two libraries, and a site with
 * a leaner one of its own should say so here instead -- it is one
 * line. It is the default because it comes from a long-lived
 * publisher, it is on Docker Hub where an execute node can reach it,
 * and anything smaller would be an image this repository had to build
 * and keep alive.
 *
 * `docker://` is not decoration: it is how HTCondor is told this names
 * a docker-style repository rather than a .sif file or an exploded
 * directory, and it is also how HTCondor knows never to put the image
 * through a file-transfer plugin.
 *
 * A wrong name here is the worst failure this file can produce: every
 * job holds with a transfer error that says nothing about the image.
 * Change it only to something you have pulled and run.
 */
export const CONTAINER_IMAGE = 'docker://continuumio/anaconda3:2024.10-1';

export interface JobSpec {
  /** Names in the sandbox, each already passing isSafeFileName. */
  inputNames: string[];
  /** Total bytes of those inputs, for the resource requests. */
  inputBytes: number;
  /** Groups one submission's jobs in the queue. */
  batchName: string;
  /** What to call this job in the list. Arbitrary user text. */
  title: string;
}

export function buildSubmitFile(spec: JobSpec): string {
  const inputs = [RUNNER_FILE, ...spec.inputNames.filter(isSafeFileName)].map(quote);

  // `: >` before anything else, in `arguments` rather than inside the
  // Python, so that a runner that cannot even be parsed still fails as
  // itself instead of as a missing-output hold.
  const prepare = OUTPUT_FILES.map((f) => `: > ${f}`).join('; ');

  return [
    `# FITS statistics and preview. Generated by the FITS Previews site app;`,
    `# site policy (log location, accounting group) is applied by the access`,
    `# point and is deliberately absent here.`,
    ``,
    // The job runs inside an image that HAS astropy, rather than
    // hoping the execute node does and telling the user to ask an
    // administrator when it does not. `universe = container` is
    // optional once container_image is set, and stating it makes the
    // file say what it is.
    `universe = container`,
    `container_image = ${quote(CONTAINER_IMAGE)}`,
    ``,
    // /usr/bin/env, not the Python file: the runner arrives as an input
    // and inputs are uploaded AFTER the job is created, so naming it as
    // the executable would mean submitting against a file that does not
    // exist yet. In container universe this path is resolved INSIDE the
    // image, where it is Debian's own /usr/bin/env.
    `executable = /usr/bin/env`,
    `transfer_executable = false`,
    `arguments = "bash -c '${prepare}; exec python3 ${RUNNER_FILE}'"`,
    ``,
    `request_cpus = ${REQUEST_CPUS}`,
    `request_memory = ${requestMemoryMB(spec.inputBytes)}`,
    `request_disk = ${requestDiskKB(spec.inputBytes)}`,
    ``,
    `should_transfer_files = YES`,
    `when_to_transfer_output = ON_EXIT`,
    `transfer_input_files = ${inputs.join(',')}`,
    // Declared, so they come back by name whatever else the job left
    // lying around -- and created at the start of the job, so declaring
    // them cannot turn a failure into a hold.
    `transfer_output_files = ${OUTPUT_FILES.join(',')}`,
    ``,
    `output = stdout.txt`,
    `error = stderr.txt`,
    ``,
    // `batch_name`, NOT `JobBatchName = ...`.
    //
    // A submit file is not a ClassAd. An assignment to a name that is
    // not a submit command defines a submit MACRO and sets nothing on
    // the job, so `JobBatchName = x` leaves the job ad without a
    // JobBatchName and the constraint in app.tsx matches nothing. The
    // job list then stays empty forever, with no error anywhere.
    `batch_name = ${quote(spec.batchName)}`,
    // Custom job attributes, which is what a leading `+` means in a
    // submit file. The queue is this app's only record of what was
    // submitted, so the name the user gave a file is stored on the job
    // and read back through the projection in api.ts. If an access
    // point were to strip them the list falls back to the job id.
    `+FitsTitle = ${quote(adString(spec.title))}`,
    ``,
    `queue 1`,
    ``,
  ].join('\n');
}

/** A batch name grouping one submission's jobs. Safe by construction. */
export function batchNameFor(mode: string, when = new Date()): string {
  const stamp = when.toISOString().replace(/[-:T]/g, '').slice(0, 14);
  const kind = mode === 'composite' ? 'colour' : 'each';
  return `${BATCH_PREFIX}${kind}-${stamp}`;
}

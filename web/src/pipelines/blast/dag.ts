// The .dag file, and the node submit files it names.
//
// A DAG with no edges is still worth having here. The graph is not the
// point -- every node is independent and could have been a `queue N`.
// What the DAG buys is the SPOOL: one directory, uploaded once, that
// every node reads the database out of.
//
// Everything in it is referenced by basename because the spool is one
// flat directory, and nothing can be added to it after submission, so
// a name that is wrong here is a node that fails at run time with a
// missing input rather than a submission that is refused.

import { buildSubmitFile, type JobSpec } from './blast';

/** The file name the DAG itself is written as. */
export const DAG_NAME = 'search.dag';

/** The submit file for node i, by the name it has in the spool. */
export function nodeSubmitName(i: number): string {
  return `node${i}.sub`;
}

/** One node: its submit file name and what it searches. */
export interface Node {
  name: string;
  submitName: string;
  spec: JobSpec;
}

/**
 * Lay the queries out over nodes.
 *
 * With the database spooled once this is only about parallelism, so
 * the grouping is simple: `perNode` files each, in order. The earlier
 * version of this example had to solve a packing problem here, because
 * every job re-uploaded the database and the budget was the user's
 * uplink.
 */
export function planNodes(
  queryNames: string[],
  queryBytes: number[],
  base: Omit<JobSpec, 'queryNames' | 'queryBytes'>,
  perNode: number,
): Node[] {
  const nodes: Node[] = [];
  for (let i = 0; i < queryNames.length; i += perNode) {
    const names = queryNames.slice(i, i + perNode);
    const bytes = queryBytes.slice(i, i + perNode).reduce((a, b) => a + b, 0);
    const n = nodes.length;
    nodes.push({
      name: `q${n}`,
      submitName: nodeSubmitName(n),
      spec: { ...base, queryNames: names, queryBytes: bytes },
    });
  }
  return nodes;
}

/**
 * The .dag file.
 *
 * RETRY on every node, because the failures this workflow actually
 * sees are an evicted job and a node that was missing BLAST+ -- the
 * first is worth retrying and the second fails the same way twice,
 * quickly. No PARENT/CHILD lines: the nodes do not depend on each
 * other, and writing edges that do not exist would say they do.
 */
export function buildDagFile(nodes: Node[]): string {
  const lines = [
    `# BLAST search. Generated by the BLAST pipeline of a site app.`,
    `# One node per group of query files; all independent.`,
    `#`,
    `# The database is NOT named here. It is in this workflow's spooled`,
    `# directory, which is where DAGMan runs, so each node's submit file`,
    `# names it by basename and it is already present.`,
    ``,
  ];
  for (const n of nodes) {
    lines.push(`JOB ${n.name} ${n.submitName}`);
  }
  lines.push(``);
  for (const n of nodes) {
    lines.push(`RETRY ${n.name} 2`);
  }
  lines.push(``);
  return lines.join('\n');
}

/** The node submit files, keyed by the name each has in the spool. */
export function buildNodeFiles(nodes: Node[]): Record<string, string> {
  const files: Record<string, string> = {};
  for (const n of nodes) {
    files[n.submitName] = buildSubmitFile(n.spec);
  }
  return files;
}
